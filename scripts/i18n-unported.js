#!/usr/bin/env node
// Regenerates scripts/i18n-unported.json: the English strings that upstream translates and this fork
// does not use yet.
//
// The point of deriving it instead of hand-maintaining it: an entry is allowed to be "unused" only
// because upstream really has that string and this fork has not ported the feature that shows it. It
// cannot be used to excuse a typo, a renamed string, or an entry somebody invented. If upstream drops
// the string, it disappears from this file on the next run and the checker fails again.
//
// Run it after porting or renaming strings:  node scripts/i18n-unported.js
const fs = require('node:fs');
const path = require('node:path');
const { execFileSync } = require('node:child_process');
const { sourceKeys, loadDict } = require('./i18n-check');

const ROOT = path.join(__dirname, '..');
const SITE = path.join(ROOT, 'site');
const OUT = path.join(__dirname, 'i18n-unported.json');
const UPSTREAM = process.env.UPSTREAM_REF || 'origin/main';

function show(rel) {
  try {
    return execFileSync('git', ['show', `${UPSTREAM}:${rel}`], { cwd: ROOT, encoding: 'utf8', maxBuffer: 1 << 28 });
  } catch {
    console.error(`error: cannot read ${rel} from ${UPSTREAM}. Fetch it first, or set UPSTREAM_REF.`);
    process.exit(2);
  }
}

const forkKeys = sourceKeys(fs.readFileSync(path.join(SITE, 'index.html'), 'utf8'));
const upKeys = sourceKeys(show('site/index.html'));

// Only strings upstream actually shows and translates can be "not ported yet".
const dicts = fs.readdirSync(path.join(SITE, 'i18n')).filter((f) => f.endsWith('.js'));
const translatedUpstream = new Set();
for (const f of dicts) {
  let dict;
  try {
    dict = loadDictFrom(show(`site/i18n/${f}`));
  } catch {
    continue; // a language this fork has that upstream does not
  }
  for (const k of Object.keys(dict)) if (upKeys.has(k)) translatedUpstream.add(k);
}

const keys = [...translatedUpstream].filter((k) => !forkKeys.has(k)).sort();
fs.writeFileSync(OUT, JSON.stringify({
  note: 'English strings upstream translates for features this fork has not ported. Generated by scripts/i18n-unported.js from ' + UPSTREAM + '; do not edit by hand. These entries are kept in the dictionaries because they are finished translations, and are not counted as unused.',
  upstream: UPSTREAM,
  keys,
}, null, 1) + '\n');
console.log(`wrote ${path.relative(ROOT, OUT)}: ${keys.length} unported strings (upstream ${UPSTREAM} has ${upKeys.size}, this fork ${forkKeys.size})`);

function loadDictFrom(src) {
  const vm = require('node:vm');
  const window = {};
  vm.runInNewContext(src, { window });
  const lang = Object.keys(window.I18N || {})[0];
  return (window.I18N || {})[lang] || {};
}
